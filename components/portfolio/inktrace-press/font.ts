/** The width of `text`, each font pixel drawn `scale` sheet pixels square. */
export function measure(text:string,f:Face=SMALL,scale=1){
 let w=0;for(const ch of text){const g=f.glyphs[ch];if(!g)throw new Error(`no glyph '${ch}'`);w+=g[0].length+f.gap;}
 return Math.max(0,w-f.gap)*scale;
}

/** Prints `text` with its top-left at (x,y). Returns the x just past the last glyph. */
export function print(sheet:Sheet,text:string,x:number,y:number,ink:number,f:Face=SMALL,scale=1){
 for(const ch of text){
  const g=f.glyphs[ch];if(!g)throw new Error(`no glyph '${ch}'`);
  g.forEach((row,j)=>{for(let i=0;i<row.length;i++)if(row[i]==='#')sheet.fill(x+i*scale,y+j*scale,x+i*scale+scale-1,y+j*scale+scale-1,ink);});
  x+=(g[0].length+f.gap)*scale;
 }
 return x-f.gap*scale;
}
