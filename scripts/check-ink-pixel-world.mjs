 assert.equal(await b.run('document.querySelectorAll("audio,video,iframe").length'),0);
 assert(await b.run('document.documentElement.scrollWidth<=innerWidth'));
 report.push('1440: event drawer, no audio/video/iframe, no horizontal overflow.');
 const progress=()=>b.run('document.querySelector("footer>div:last-child>span").style.width');
 const pausedAt=await progress();await b.delay(400);assert.equal(await progress(),pausedAt);
 report.push('Choosing an event pauses the film for reading.');
 await b.run(`document.querySelectorAll('[role="tab"]')[3].click()`);await b.delay(13000);
 await b.shot(`${dir}/04-wiki-1440.png`);
