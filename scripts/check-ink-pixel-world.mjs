 assert(await b.run(`document.activeElement===${q('Open InkTrace demo')}`));
 await click('Open InkTrace demo');await b.delay(850);
 for(const index of [1,2,0,3,2,0])await b.run(`document.querySelectorAll('[role="tab"]')[${index}].click()`);
 await b.delay(500);assert(await b.run('document.querySelector("[role=tabpanel]").textContent.includes("THE OPEN ARCHIVE")'));
 report.push('Rapid chapter changes settle on the final selection; close returns focus.');
 await b.send('Emulation.setEmulatedMedia',{features:[{name:'prefers-reduced-motion',value:'reduce'}]});
 await b.until(`!!${q('Next keyframe')}`);assert(await b.run(`!!${q('Next keyframe')}`));
