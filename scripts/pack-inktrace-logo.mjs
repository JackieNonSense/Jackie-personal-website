// Packs the InkTrace book mark into a tone map for the press run's closing plate:
// the real logo, cropped to the book, resampled, and stored as one hex digit of
// ink coverage (0 paper … f solid) per pixel. The press screens it into halftone.
// Usage: node scripts/pack-inktrace-logo.mjs <path/to/email-logo.png>
import sharp from 'sharp';
import {writeFile} from 'node:fs/promises';

const source=process.argv[2];
if(!source)throw new Error('Pass the InkTrace logo PNG (apps/web/public/email-logo.png in the InkTrace repo).');
const output='components/portfolio/inktrace-press/logo.ts',WIDTH=124;

const {data,info}=await sharp(source).ensureAlpha().raw().toBuffer({resolveWithObject:true});
const ink=(i)=>data[i+3]<40?0:1-(data[i]*.299+data[i+1]*.587+data[i+2]*.114)/255;
let x0=info.width,y0=info.height,x1=0,y1=0;
for(let y=0;y<info.height;y++)for(let x=0;x<info.width;x++)if(ink((y*info.width+x)*4)>.08){x0=Math.min(x0,x);y0=Math.min(y0,y);x1=Math.max(x1,x);y1=Math.max(y1,y);}
const crop={left:x0-2,top:y0-2,width:x1-x0+5,height:y1-y0+5};
const height=Math.round(WIDTH*crop.height/crop.width);
const {data:small}=await sharp(source).extract(crop).flatten({background:'#ffffff'}).resize(WIDTH,height,{kernel:'lanczos3'}).greyscale().raw().toBuffer({resolveWithObject:true});
const rows=[];
for(let y=0;y<height;y++){
 let row='';
 for(let x=0;x<WIDTH;x++){
  const tone=1-small[y*WIDTH+x]/255;
  row+=(tone<.06?0:Math.min(15,Math.round(tone*15))).toString(16);
 }
 rows.push(row);
}
await writeFile(output,`// Generated by scripts/pack-inktrace-logo.mjs from the InkTrace book mark.
// One hex digit of ink coverage per pixel (0 paper … f solid). Do not edit by hand.
export const LOGO={w:${WIDTH},h:${height},rows:[
${rows.map(r=>` '${r}',`).join('\n')}
]} as const;
`);
console.log(`wrote ${output} (${WIDTH}×${height})`);
